"""Saha End-to-End Demo Proof Script.

Fully model-driven workflow:
1. Calls PLANNER model (generate_plan) for the goal:
   "Create two small data files with different facts about Hyderabad, combine them into a summary file, and check that https://example.com is reachable."
2. File steps carry `content_brief`; WORKER model generates actual file content.
3. Probes deterministically verify file hashes and status codes against physical reality.
4. Sabotages by deleting one file from disk (leaving ledger untouched).
5. Calls resume_task:
   - Reality probe detects missing file.
   - FAST model generates plain-English explanation into drift_events table.
   - Replaced steps transition to `superseded` (never deleted).
   - PLANNER model appends repair steps.
   - WORKER model executes repairs; probes verify reality.
6. Prints the complete audit ledger (showing original, superseded, and repair steps).
7. Prints llm_calls telemetry grouped by role (PLANNER, WORKER, FAST).
"""

import os
import sys
from pathlib import Path

# Set up UTF-8 console output for Windows
sys.stdout.reconfigure(encoding="utf-8")

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from backend.db import get_llm_metrics
from backend.executor import run_task
from backend.ledger import Ledger
from backend.planner import generate_plan
from backend.resume import resume_task
from backend.tools.sandbox import get_workspace_dir, resolve_workspace_path
from cli.saha import print_step_table


def main():
    print("\n" + "=" * 90)
    print(" SAHA FULL MODEL-DRIVEN DEMO PROOF")
    print("=" * 90)

    goal = (
        "Create two small data files with different facts about Hyderabad, "
        "combine them into a summary file, and check that https://example.com is reachable."
    )
    print(f"\n[1] Goal: \"{goal}\"")

    task = Ledger.create_task(goal)
    print(f"    Created Task ID: {task.id}")
    print(f"    Task Workspace: workspace/{task.id}/")

    print("\n[2] Invoking PLANNER model (nvidia/Nemotron-3-Ultra-550b-a55b) to generate plan...")
    step_plans = generate_plan(goal)
    print(f"    ✔ Plan generated: {len(step_plans)} steps with content briefs.")

    steps_data = [
        {
            "intent": sp.intent,
            "tool": sp.tool,
            "args": sp.args,
            "probe": sp.probe,
        }
        for sp in step_plans
    ]
    Ledger.add_steps(task.id, steps_data)

    initial_summary = Ledger.get_task_summary(task.id)
    print_step_table(initial_summary["steps"], title=f"PLANNED STEPS (Generated by PLANNER)")

    print("[3] Executing steps: WORKER generates content, deterministic probes verify reality...")
    completed_task = run_task(task.id)
    pre_sabotage_summary = Ledger.get_task_summary(task.id)
    print_step_table(
        pre_sabotage_summary["steps"],
        title=f"BEFORE SABOTAGE: ALL STEPS VERIFIED (Status: {completed_task.status.upper()})",
    )

    # Find the first written file to sabotage
    target_rel = None
    for s in pre_sabotage_summary["steps"]:
        if s["tool"] == "write_file":
            target_rel = s["args"].get("path")
            break

    if not target_rel:
        target_rel = "facts1.txt"

    target_disk_path = resolve_workspace_path(target_rel, task_id=task.id)

    # 4. SABOTAGE: Delete file from disk without touching database ledger
    print("\n" + "!" * 90)
    print(f"[4] INJECTING SABOTAGE: Deleting workspace/{task.id}/{target_rel} directly from disk...")
    if target_disk_path.exists():
        target_disk_path.unlink()
    print(f"    Deleted file: {target_disk_path}")
    print(f"    File exists in physical reality? {target_disk_path.exists()}")
    print("    Note: The ledger database was NOT modified; ledger still logged this step as 'verified'.")
    print("!" * 90 + "\n")

    # 5. RESUME & RECONCILE
    print("[5] Invoking resume_task()...")
    print("    - Deterministic probes re-check physical reality.")
    print("    - FAST model generates plain-English explanation into drift_events table.")
    print("    - PLANNER model replans repair steps.")
    print("    - Old steps are SUPERSEDED (never deleted); new repair steps are APPENDED.")
    print("    - WORKER model executes repairs; probes verify reality.")

    resume_result = resume_task(task.id)
    drift_report = resume_result["drift_report"]

    print("\n--- Reality Probe Audit & Drift Events ---")
    print(f"Drift Detected: {drift_report['has_drift']}")
    print(f"Drifted Step Count: {drift_report['drift_count']}")
    for d in drift_report["drifted_steps"]:
        print(f"  • Event ID: {d['event_id'][:8]} | Seq {d['seq']} ({d['tool']}): {d['reason']}")
        print(f"    Fast Auditor Explanation: \"{d['explanation']}\"")

    post_resume_summary = Ledger.get_task_summary(task.id)
    print_step_table(
        post_resume_summary["steps"],
        title=f"AFTER RESUME & RECONCILIATION: FULL AUDIT TRAIL (Status: {resume_result['task']['status'].upper()})",
    )

    print("--- Final Reality Check ---")
    print(f"Target file '{target_rel}' restored in reality? {target_disk_path.exists()}")
    if target_disk_path.exists():
        print(f"File preview on disk:\n  \"{target_disk_path.read_text(encoding='utf-8').strip()[:180]}...\"")

    # 6. Display LLM Telemetry Grouped by Role
    print("\n" + "=" * 90)
    print(" LLM PERFORMANCE METRICS (From llm_calls table grouped by role)")
    print("=" * 90)
    metrics = get_llm_metrics()
    print(f"Total API Calls: {metrics['total_calls']}")
    for m in metrics["models"]:
        print(f"Role: {m['role'].upper():<8} | Model: {m['model']}")
        print(f"  Calls: {m['call_count']:<3} | Avg Latency: {m['avg_latency_ms']:>7.2f} ms | Tokens: {m['total_tokens']:>6} (prompt: {m['total_prompt_tokens']}, comp: {m['total_completion_tokens']})")
    print("=" * 90 + "\n")


if __name__ == "__main__":
    main()
